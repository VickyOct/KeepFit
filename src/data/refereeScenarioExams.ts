import { refereeLessons } from './refereeLessons';
import type { ScenarioExam } from '../refereeTypes';

type ScenarioInput = [prompt: string, whistle: boolean, answer: string, d1: string, d2: string, d3: string, explanation: string, lessonId: string, sectionId: string, reference: string];

function exam(order: number, subtitle: string, inputs: ScenarioInput[]): ScenarioExam {
  const id = `scenario-${order}`;
  if (inputs.length !== 10) throw new Error(`综合测验题数错误：${id}`);
  return {
    id, order, title: `综合模拟 ${order}`, subtitle,
    questions: inputs.map(([prompt, whistle, answer, d1, d2, d3, explanation, lessonId, studySectionId, reference], index) => {
      const section = refereeLessons.find((lesson) => lesson.id === lessonId)?.sections.find((item) => item.id === studySectionId);
      if (!section || ![section.reference, ...section.additionalReferences].includes(reference)) throw new Error(`综合题缺少讲解依据：${id}-q${index + 1}`);
      const options = [answer, d1, d2, d3];
      const shift = (order + index) % 4;
      return { id: `${id}-q${index + 1}`, prompt, whistle, options: [...options.slice(shift), ...options.slice(0, shift)], correctIndex: (4 - shift) % 4, explanation, lessonId, studySectionId, reference };
    }),
  };
}

